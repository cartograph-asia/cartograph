-- Regions: Thailand's provinces from OSM admin boundaries (admin_level 4),
-- imported by cmd/regions. Later countries (admin_level 2) go in the same
-- table with parent_id linking provinces to their country.
-- There is no PostGIS: the boundary is simplified GeoJSON text and
-- point-in-polygon runs in Go; the bounding box allows a cheap prefilter.

create table regions (
  id               int generated by default as identity primary key,
  osm_id           bigint unique,                 -- OSM relation id
  admin_level      smallint not null,             -- 4 = province, 2 = country
  country          text not null,                 -- ISO 3166-1 alpha-2, lower case, e.g. 'th'
  parent_id        int references regions(id),
  slug             text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name_en          text not null,
  name_th          text,
  boundary         text not null,                 -- simplified GeoJSON Polygon/MultiPolygon geometry, WGS 84
  min_lat          double precision not null,
  min_lng          double precision not null,
  max_lat          double precision not null,
  max_lng          double precision not null,
  land_cells       int not null default 0,        -- res-8 cells whose centre lies on land in the region
  claimed_cells    int not null default 0,        -- surveyed plots in the region, updated on claim
  last_surveyed_at timestamptz                    -- newest photo in the region, updated on upload
);

create index regions_last_surveyed_idx on regions(last_surveyed_at desc nulls last);
