-- Places: OSM city/town/village points from the extract, imported by
-- cmd/places. A plot's display name is the nearest place within 5 km,
-- copied into plots.place_name on first claim, so this table can be
-- rebuilt at any time without touching plots.

create table places (
  id        bigint generated by default as identity primary key,
  osm_type  char(1) not null check (osm_type in ('n', 'w', 'r')),
  osm_id    bigint not null,
  kind      text not null check (kind in ('city', 'town', 'village')),
  name_en   text not null,   -- name:en, else a romanised name, else name
  name_th   text,            -- name:th, else name when it is Thai
  lat       double precision not null,
  lng       double precision not null,
  region_id int references regions(id) on delete set null,
  unique (osm_type, osm_id)
);

create index places_lat_lng_idx on places(lat, lng);
