-- Plot of the week, set by hand in SQL. The current entry is the one with the
-- latest starts_at that has started and not ended. Without one, the front
-- page falls back to the most recent first survey.

create table featured (
  id         int generated by default as identity primary key,
  photo_id   uuid not null references photos(id) on delete cascade,
  body       text not null default '',     -- short editorial text, plain
  starts_at  timestamptz not null default now(),
  ends_at    timestamptz,                  -- null = until replaced
  created_at timestamptz not null default now(),
  check (ends_at is null or ends_at > starts_at)
);

create index featured_starts_idx on featured(starts_at desc);
